-- Postgres schema for a fresh database (mirrors the SQLite schema at version 26).
-- Tables are ordered so that referenced tables exist first.

CREATE TABLE ban_appeals (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        channel_id TEXT,
        reason TEXT,
        status TEXT DEFAULT 'pending' CHECK(status IN ('pending', 'accepted', 'rejected')),
        moderator_id TEXT,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
        resolved_at TEXT DEFAULT NULL
      );
CREATE TABLE crosspost_incidents (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        original_channel_id TEXT NOT NULL,
        original_message_content TEXT,
        crosspost_channel_id TEXT NOT NULL,
        crosspost_message_content TEXT,
        similarity_score REAL NOT NULL,
        action_taken TEXT NOT NULL CHECK(action_taken IN ('deleted', 'warned')),
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE filter_violations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        word_matched TEXT NOT NULL,
        tier TEXT NOT NULL,
        message_content TEXT,
        channel_id TEXT NOT NULL,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE filter_whitelist (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        word TEXT NOT NULL,
        added_by TEXT,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE giveaways (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        channel_id TEXT NOT NULL,
        message_id TEXT,
        host_id TEXT NOT NULL,
        title TEXT DEFAULT '🎉 GIVEAWAY 🎉',
        prize TEXT NOT NULL,
        description TEXT,
        color TEXT DEFAULT NULL,
        winner_count INTEGER DEFAULT 1,
        winners TEXT DEFAULT NULL,
        ends_at TEXT NOT NULL,
        ended INTEGER DEFAULT 0,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      , claim_time INTEGER DEFAULT NULL, claim_deadline TEXT DEFAULT NULL, claim_action TEXT DEFAULT 'reroll');
CREATE TABLE guild_settings (
        guild_id TEXT PRIMARY KEY,
        moderator_role_id TEXT,
        crosspost_threshold INTEGER DEFAULT 80,
        crosspost_window_hours INTEGER DEFAULT 48,
        warning_threshold INTEGER DEFAULT 3,
        exempt_channels TEXT DEFAULT '[]',
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
        updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      , warn_log_channel_id TEXT DEFAULT NULL, warn_role_id TEXT DEFAULT NULL, crosspost_first_message TEXT DEFAULT NULL, crosspost_repeat_message TEXT DEFAULT NULL, warn_public_message TEXT DEFAULT NULL, crosspost_detection_seconds INTEGER DEFAULT 30, ban_log_channel_id TEXT DEFAULT NULL, crosspost_kick_count INTEGER DEFAULT 3, crosspost_kick_window_minutes INTEGER DEFAULT 60, ban_role_id TEXT DEFAULT NULL, modmail_enabled INTEGER DEFAULT 0, modmail_category_id TEXT DEFAULT NULL, modactions_role_id TEXT DEFAULT NULL, file_block_enabled INTEGER DEFAULT 1, blocked_extensions TEXT DEFAULT NULL, banreason_role_id TEXT DEFAULT NULL, custom_warn_reasons TEXT DEFAULT NULL, bot_status_message TEXT DEFAULT NULL, ticket_category_id TEXT DEFAULT NULL, ticket_admin_role_id TEXT DEFAULT NULL, ticket_log_channel_id TEXT DEFAULT NULL, loader_file_name TEXT DEFAULT NULL, ticket_open_message TEXT DEFAULT NULL, license_required_role_ids TEXT DEFAULT NULL, license_role_prices TEXT DEFAULT NULL, banned_domains TEXT DEFAULT NULL, filter_enabled INTEGER DEFAULT 1, soft_slur_threshold INTEGER DEFAULT 3, soft_slur_window_minutes INTEGER DEFAULT 60, image_only_channels TEXT DEFAULT NULL, appeal_category_id TEXT DEFAULT NULL, appeal_enabled INTEGER DEFAULT 0, server_invite_code TEXT DEFAULT NULL, giveaway_host_role_id TEXT DEFAULT NULL, giveaway_host_user_ids TEXT DEFAULT NULL, giveaway_log_channel_id TEXT DEFAULT NULL, giveaway_ping_role_id TEXT DEFAULT NULL, giveaway_channel_id TEXT DEFAULT NULL);
CREATE TABLE license_tickets (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        channel_id TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open', 'closed')),
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
        closed_at TEXT DEFAULT NULL,
        closed_by TEXT DEFAULT NULL
      );
CREATE TABLE message_cache (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        channel_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        message_id TEXT NOT NULL UNIQUE,
        content TEXT NOT NULL,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE mod_actions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        moderator_id TEXT NOT NULL,
        action_type TEXT NOT NULL,
        target_id TEXT NOT NULL,
        details TEXT,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE modmail_threads (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        channel_id TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open', 'closed')),
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
        closed_at TEXT DEFAULT NULL,
        closed_by TEXT DEFAULT NULL
      );
CREATE TABLE self_role_panels (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        channel_id TEXT NOT NULL,
        message_id TEXT NOT NULL,
        title TEXT DEFAULT 'Self Roles',
        description TEXT DEFAULT NULL,
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE temp_bans (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        moderator_id TEXT NOT NULL,
        reason TEXT,
        duration_days INTEGER NOT NULL,
        banned_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
        unban_at TEXT NOT NULL,
        unbanned INTEGER DEFAULT 0
      , unbanned_at TEXT DEFAULT NULL);
CREATE TABLE warnings (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        user_id TEXT NOT NULL,
        moderator_id TEXT NOT NULL,
        reason TEXT NOT NULL,
        type TEXT NOT NULL CHECK(type IN ('manual', 'crosspost')),
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      , message_content TEXT DEFAULT NULL);
CREATE TABLE word_filter (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id TEXT NOT NULL,
        word TEXT NOT NULL,
        tier TEXT NOT NULL CHECK(tier IN ('hard', 'soft', 'auto_delete')),
        created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      , whole_word INTEGER DEFAULT 0);
CREATE TABLE giveaway_claims (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        giveaway_id INTEGER NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
        user_id TEXT NOT NULL,
        status TEXT NOT NULL CHECK(status IN ('claimed', 'expired')),
        updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE giveaway_entries (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        giveaway_id INTEGER NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
        user_id TEXT NOT NULL,
        entered_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
      );
CREATE TABLE self_role_options (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        panel_id INTEGER NOT NULL REFERENCES self_role_panels(id) ON DELETE CASCADE,
        role_id TEXT NOT NULL,
        label TEXT DEFAULT NULL,
        emoji TEXT DEFAULT NULL,
        description TEXT DEFAULT NULL,
        sort_order INTEGER DEFAULT 0
      );

CREATE INDEX idx_ban_appeals_channel ON ban_appeals(channel_id);
CREATE INDEX idx_ban_appeals_guild_user ON ban_appeals(guild_id, user_id);
CREATE INDEX idx_ban_appeals_status ON ban_appeals(guild_id, status);
CREATE INDEX idx_crosspost_guild_user ON crosspost_incidents(guild_id, user_id);
CREATE INDEX idx_filter_violations_created ON filter_violations(created_at);
CREATE INDEX idx_filter_violations_guild_user ON filter_violations(guild_id, user_id);
CREATE UNIQUE INDEX idx_filter_whitelist_guild_word ON filter_whitelist(guild_id, word);
CREATE INDEX idx_giveaway_claims_status ON giveaway_claims(giveaway_id, status);
CREATE UNIQUE INDEX idx_giveaway_claims_unique ON giveaway_claims(giveaway_id, user_id);
CREATE INDEX idx_giveaway_entries_giveaway ON giveaway_entries(giveaway_id);
CREATE UNIQUE INDEX idx_giveaway_entries_unique ON giveaway_entries(giveaway_id, user_id);
CREATE INDEX idx_giveaways_channel ON giveaways(channel_id, ended);
CREATE INDEX idx_giveaways_expires ON giveaways(ended, ends_at);
CREATE INDEX idx_giveaways_guild ON giveaways(guild_id, ended);
CREATE INDEX idx_license_tickets_channel ON license_tickets(channel_id);
CREATE INDEX idx_license_tickets_guild_user ON license_tickets(guild_id, user_id);
CREATE INDEX idx_license_tickets_status ON license_tickets(guild_id, status);
CREATE INDEX idx_message_cache_created ON message_cache(created_at);
CREATE INDEX idx_message_cache_lookup ON message_cache(guild_id, user_id, channel_id);
CREATE INDEX idx_mod_actions_guild_mod ON mod_actions(guild_id, moderator_id);
CREATE INDEX idx_mod_actions_guild_target ON mod_actions(guild_id, target_id);
CREATE INDEX idx_mod_actions_type ON mod_actions(guild_id, action_type);
CREATE INDEX idx_modmail_channel ON modmail_threads(channel_id);
CREATE INDEX idx_modmail_guild_user ON modmail_threads(guild_id, user_id);
CREATE INDEX idx_modmail_status ON modmail_threads(status);
CREATE INDEX idx_self_role_options_panel ON self_role_options(panel_id);
CREATE INDEX idx_self_role_panels_guild ON self_role_panels(guild_id);
CREATE INDEX idx_self_role_panels_message ON self_role_panels(message_id);
CREATE INDEX idx_temp_bans_due ON temp_bans(guild_id, unbanned, unban_at);
CREATE INDEX idx_warnings_created ON warnings(created_at);
CREATE INDEX idx_warnings_guild_user ON warnings(guild_id, user_id);
CREATE INDEX idx_word_filter_guild_tier ON word_filter(guild_id, tier);
CREATE UNIQUE INDEX idx_word_filter_guild_word ON word_filter(guild_id, word);
